import assert from 'node:assert/strict';
import {chromium} from '../tidepool-jelly/node_modules/playwright-core/index.mjs';
import {mkdirSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const offline=process.argv.includes('--offline'),out='output/ppt-revision-2/page04'+(offline?'/offline':'');
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/shang/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe',args:['--no-sandbox','--force_low_power_gpu']});
const report={offline,errors:[],external:[]};
try{
 const p=await browser.newPage({viewport:{width:1536,height:864}});
 p.on('pageerror',e=>report.errors.push(e.message));
 if(offline)p.on('request',r=>{if(!/^(file:|data:|blob:)/.test(r.url()))report.external.push(r.url());});
 await p.addInitScript(()=>{if(!localStorage.getItem('inari-hud-v36'))localStorage.setItem('inari-hud-v36',JSON.stringify({wide:{minimap:{x:86,y:1,scale:98,opacity:100}},compact:{}}));});
 await p.goto(offline?pathToFileURL(resolve('伏見稻荷・星旅.html')).href:'http://127.0.0.1:4197');
 const ready=()=>p.waitForFunction(()=>window.inari?.state.ready,null,{timeout:120000});
 await ready();
 await p.evaluate(()=>{inari.setRenderQuality('clear');inari.setMode('walk');inari.teleport(-59,-.3);inari.setView(-1.52,-.08,5.7);});
 await p.waitForTimeout(600);
 await p.screenshot({path:out+'/expanded.png'});
 const toggle=id=>p.locator('[data-fold="'+id+'"]').click();
 await toggle('actions');await p.waitForFunction(()=>document.querySelector('#hudActions').getBoundingClientRect().top>innerHeight);
 assert.equal(await p.locator('[data-fold=routes]').getAttribute('aria-expanded'),'true');
 await toggle('routes');
 await p.waitForFunction(()=>document.querySelector('#destinations').getBoundingClientRect().top>innerHeight);
 report.folded=await p.evaluate(()=>({...inari.hud.folders.stats,routesInert:document.querySelector('#destinations').inert,actionsInert:document.querySelector('#hudActions').inert}));
 assert.deepEqual(report.folded,{quiet:false,routes:true,actions:true,routesInert:true,actionsInert:true});
 await p.waitForTimeout(330);await p.screenshot({path:out+'/folded.png'});
 await p.keyboard.press('KeyU');
 const selected=p.locator('#hudTarget');await selected.selectOption('minimap');
 assert.ok(await p.locator('#hudEnabled').isChecked());
 await p.locator('#hudEnabled').uncheck();
 await p.screenshot({path:out+'/settings.png'});
 await p.getByRole('button',{name:'完成',exact:true}).click();
 await p.waitForFunction(()=>getComputedStyle(document.querySelector('#hudMinimap')).visibility==='hidden');
 await p.reload();await ready();
 await p.waitForFunction(()=>inari.hud.folders.stats.routes&&inari.hud.folders.stats.actions);
 report.saved=await p.evaluate(()=>({folds:inari.hud.folders.stats,config:inari.hud.editor.stats.widgets.minimap.config,hidden:getComputedStyle(document.querySelector('#hudMinimap')).visibility==='hidden'}));
 assert.equal(report.saved.config.x,86);assert.equal(report.saved.config.enabled,false);assert.equal(report.saved.hidden,true);
 await p.keyboard.press('KeyU');await selected.selectOption('minimap');await p.locator('#hudEnabled').check();
 await p.getByRole('button',{name:'完成',exact:true}).click();
 await toggle('routes');await p.waitForFunction(()=>document.querySelector('#destinations').getBoundingClientRect().top<innerHeight);
 await p.setViewportSize({width:390,height:844});
 await p.evaluate(()=>{inari.setMode('walk');inari.teleport(-60,-.3);inari.setView(-1.52,-.08,6);});
 await p.waitForTimeout(550);await p.screenshot({path:out+'/mobile.png'});
 assert.equal(await p.locator('[data-fold=actions]').getAttribute('aria-expanded'),'false');
 await toggle('quiet');
 await p.waitForFunction(()=>document.body.classList.contains('hud-quiet'));
 report.quiet=await p.evaluate(()=>({shown:[...document.querySelectorAll('.hud-widget')].filter(n=>n.getBoundingClientRect().width&&getComputedStyle(n).visibility==='visible').length,key:document.querySelector('[data-fold=quiet]').textContent.trim(),width:document.documentElement.scrollWidth}));
 await p.waitForTimeout(330);await p.screenshot({path:out+'/clean-mobile.png'});
 assert.deepEqual(report.quiet,{shown:0,key:'顯示介面',width:390});
 await p.keyboard.press('KeyI');await p.waitForFunction(()=>!document.body.classList.contains('hud-quiet'));
 await toggle('actions');await p.waitForFunction(()=>!document.querySelector('#hudActions').inert);
 assert.deepEqual(report.errors,[]);assert.deepEqual(report.external,[]);
}finally{writeFileSync(out+'/qa.json',JSON.stringify(report,null,2));await browser.close();}
